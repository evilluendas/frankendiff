import fs from 'node:fs'
import path from 'node:path'
import { createElement, type ReactElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import DiffView from '@/components/DiffView'
import ChapterView from '@/components/ChapterView'
import { readChapter, readChapterForEdition, readChapterList } from '@/lib/data'
import { Edition } from '@/lib/types'

/**
 * HTML snapshots of every page's text, committed so that a PR shows how it
 * changes the markup readers get: tests/snapshots/diff/<slug>.html for each
 * Diff page, tests/snapshots/read/<edition>/<slug>.html for each Read page.
 *
 * Each file is the page's content component (DiffView or ChapterView)
 * rendered with the same props the page passes; the header, navigation and
 * sidebar are left out, and so is the cover, which CoverView writes by hand.
 * Class attributes are dropped and icons reduced to <svg/>; everything else is
 * kept, pretty-printed: containers are indented one tag per line, and a
 * paragraph stays on one line so a change to it diffs word by word.
 *
 * `npm run snapshot` rewrites the files; tests/snapshot.test.ts fails while
 * they are out of date. Run `npm run preprocess` first (both scripts do).
 */

export const SNAPSHOT_DIR = path.resolve(__dirname, '..', 'tests', 'snapshots')

const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr'])
const BLOCK = new Set([
  'address', 'article', 'aside', 'blockquote', 'dd', 'details', 'div', 'dl', 'dt', 'figcaption', 'figure', 'footer',
  'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'header', 'hr', 'li', 'main', 'nav', 'ol', 'p', 'pre', 'section', 'summary',
  'table', 'tbody', 'td', 'tfoot', 'th', 'thead', 'tr', 'ul',
])

interface Element { tag: string; open: string; children: Node[] }
type Node = string | Element

/** Parses React's static markup (well-formed, text and attributes escaped) into a tree, dropping class attributes. */
function parse(html: string): Node[] {
  const root: Element = { tag: '', open: '', children: [] }
  const stack = [root]
  for (const m of html.matchAll(/<\/([\w-]+)>|<([\w-]+)([^>]*?)\/?>|[^<]+/g)) {
    const top = stack[stack.length - 1]
    if (m[1]) {
      if (top.tag !== m[1]) throw new Error(`unbalanced </${m[1]}> inside <${top.tag}>`)
      stack.pop()
    } else if (m[2]) {
      const el: Element = { tag: m[2], open: `<${m[2]}${m[3].replace(/\s+class="[^"]*"/g, '')}>`, children: [] }
      top.children.push(el)
      if (!VOID.has(el.tag) && !m[0].endsWith('/>')) stack.push(el)
    } else {
      top.children.push(m[0])
    }
  }
  return root.children
}

function inline(node: Node): string {
  if (typeof node === 'string') return node
  if (node.tag === 'svg') return '<svg/>'
  if (VOID.has(node.tag)) return node.open
  return `${node.open}${node.children.map(inline).join('')}</${node.tag}>`
}

/** An element printed over several lines: one that holds a block element somewhere below it. */
function isContainer(node: Node): node is Element {
  return typeof node !== 'string' && node.tag !== 'svg' &&
    node.children.some((c) => typeof c !== 'string' && (BLOCK.has(c.tag) || isContainer(c)))
}

function pretty(nodes: Node[], depth = 0, lines: string[] = []): string[] {
  const indent = '  '.repeat(depth)
  let run = ''
  const flush = () => {
    if (run.trim()) lines.push(indent + run)
    run = ''
  }
  for (const node of nodes) {
    if (isContainer(node)) {
      flush()
      lines.push(indent + node.open)
      pretty(node.children, depth + 1, lines)
      lines.push(`${indent}</${node.tag}>`)
    } else if (typeof node !== 'string' && BLOCK.has(node.tag)) {
      flush()
      lines.push(indent + inline(node))
    } else {
      run += inline(node)
    }
  }
  flush()
  return lines
}

function snapshot(url: string, element: ReactElement): string {
  const header = `<!-- ${url}: generated by \`npm run snapshot\`, do not edit -->`
  return [header, ...pretty(parse(renderToStaticMarkup(element)))].join('\n') + '\n'
}

/** Every snapshot, keyed by its path relative to SNAPSHOT_DIR. */
export function renderSnapshots(): Map<string, string> {
  const files = new Map<string, string>()
  for (const ch of readChapterList()) {
    const editions = ch.editions as Edition[]
    // Chapters diffed inside another unit have no Diff page of their own (they redirect)
    if (!ch.diffUnit) {
      files.set(`diff/${ch.slug}.html`, snapshot(`/diff/${ch.slug}`, createElement(DiffView, { groups: readChapter(ch.slug), available: editions })))
    }
    for (const edition of editions) {
      const groups = readChapterForEdition(ch.slug, edition)
      if (groups.some((g) => g.paragraphs[edition]?.[0]?.elementType === 'book-title')) continue
      files.set(`read/${edition}/${ch.slug}.html`, snapshot(`/${edition}/chapter/${ch.slug}`, createElement(ChapterView, { groups, edition })))
    }
  }
  return files
}

if (require.main === module) {
  const files = renderSnapshots()
  fs.rmSync(SNAPSHOT_DIR, { recursive: true, force: true })
  for (const [file, html] of files) {
    fs.mkdirSync(path.dirname(path.join(SNAPSHOT_DIR, file)), { recursive: true })
    fs.writeFileSync(path.join(SNAPSHOT_DIR, file), html)
  }
  console.log(`Wrote ${files.size} snapshots to ${path.relative(process.cwd(), SNAPSHOT_DIR)}/`)
}
